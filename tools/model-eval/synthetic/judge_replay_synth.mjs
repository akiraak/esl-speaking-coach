// マルチターン再生のブラインド A/B 判定。
// 学習者の発話は両者同一で、AI ターンだけが違う「同じ会話の 2 バージョン」を窓ごとに比べる。
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { anthropicJudge, sleep } from "./lib.mjs";

const DIR = new URL(".", import.meta.url).pathname;
const CONV_SYSTEM = readFileSync(`${DIR}fixtures/system-conversation.txt`, "utf8");
const replay = JSON.parse(readFileSync(`${DIR}results-replay-synth.json`, "utf8"));
const OUT = `${DIR}results-judge-replay-synth.json`;

const BASELINE = "sonnet-5";
const CANDIDATE = "haiku-4-5";
const WINDOW = 3; // AI ターン 3 つ分を 1 窓として比べる

const verdictSchema = {
  type: "object",
  properties: {
    a_score: { type: "integer" }, b_score: { type: "integer" },
    winner: { type: "string", enum: ["A", "B", "tie"] },
    rationale_ja: { type: "string" },
  },
  required: ["a_score", "b_score", "winner", "rationale_ja"],
  additionalProperties: false,
};

const judgeSystem = `You are an expert evaluator for an iOS ESL speaking-practice app. The app scripts a two-character English conversation ("ESL Group") with one LLM. Below is the production spec, then two versions (A and B) of the SAME conversation segment: the learner lines are identical utterances (from speech recognition, possibly noisy); only the AI script lines differ, because each version was generated by a different hidden model turn-by-turn.

<spec>
${CONV_SYSTEM}
</spec>

Judge which version is the better conversation for a Japanese adult ESL learner over the whole segment:
- Flow and coherence: do the AI turns react to what the learner actually said, keep context from earlier turns, avoid repetition?
- Naturalness and warmth of the small talk; character consistency (Chobi = calm warm host, Naruko = cheerful fellow learner).
- Fit for the learner: simple English, short turns, always handing the conversation back.

Score each version 1-10. winner is the better one, or "tie" if genuinely comparable. Write rationale_ja as 2-4 short sentences in Japanese.`;

// AI ターンと学習者発話を交互に並べた「会話の見た目」を作る
function segmentText(session, from, to) {
  const lines = [];
  for (let i = from; i < to && i < session.turns.length; i++) {
    const turn = session.turns[i];
    if (turn.error) continue;
    lines.push(turn.text);
    if (i < session.learnerTurns.length) lines.push(`Learner: ${session.learnerTurns[i]}`);
  }
  return lines.join("\n");
}

const toCandidate = (winner, candidateIs) =>
  winner === "tie" ? "tie" : winner === candidateIs ? "candidate" : "baseline";

const results = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")) : {};

for (const replayId of Object.keys(replay[BASELINE] ?? {})) {
  const base = replay[BASELINE][replayId];
  const cand = replay[CANDIDATE]?.[replayId];
  if (!base?.done || !cand?.done) { console.log(`skip ${replayId}（生成が揃っていない）`); continue; }
  results[replayId] ??= [];
  const windows = [];
  for (let start = 0; start < base.turns.length; start += WINDOW) {
    windows.push([start, Math.min(start + WINDOW, base.turns.length)]);
  }
  for (const [wi, [from, to]] of windows.entries()) {
    if (results[replayId][wi]) continue;
    const aSeg = segmentText(base, from, to);
    const bSeg = segmentText(cand, from, to);
    if (!aSeg.trim() || !bSeg.trim()) { results[replayId][wi] = { error: "空の窓" }; continue; }
    process.stdout.write(`${replayId} 窓${wi}（turn ${from}-${to - 1}） ... `);
    try {
      const verdicts = [];
      for (const [aText, bText, candidateIs] of [
        [aSeg, bSeg, "B"],
        [bSeg, aSeg, "A"],
      ]) {
        const { result } = await anthropicJudge({
          system: judgeSystem, schema: verdictSchema,
          messages: [{
            role: "user",
            content: `## Topic\n${base.topicTitle}\n\n## Version A\n\n${aText}\n\n## Version B\n\n${bText}`,
          }],
        });
        verdicts.push({ ...result, candidateIs, outcome: toCandidate(result.winner, candidateIs) });
        await sleep(400);
      }
      const [v1, v2] = verdicts;
      const agreed = v1.outcome === v2.outcome ? v1.outcome : "tie";
      results[replayId][wi] = { from, to, verdicts, outcome: agreed };
      console.log(`${agreed}${v1.outcome !== v2.outcome ? "（不一致→tie）" : ""}`);
    } catch (error) {
      results[replayId][wi] = { error: String(error).slice(0, 200) };
      console.log(`ERROR ${String(error).slice(0, 100)}`);
    }
    writeFileSync(OUT, JSON.stringify(results, null, 2));
  }
}

console.log("\n== マルチターン再生 A/B 集計（baseline = claude-sonnet-5）==");
const tally = { candidate: 0, baseline: 0, tie: 0, error: 0 };
for (const [rid, windows] of Object.entries(results)) {
  const local = { candidate: 0, baseline: 0, tie: 0 };
  for (const w of windows) {
    if (!w || w.error) { tally.error++; continue; }
    tally[w.outcome]++; local[w.outcome]++;
  }
  console.log(`  ${rid.padEnd(18)} 候補勝ち ${local.candidate} / 現行勝ち ${local.baseline} / 引分 ${local.tie}`);
}
console.log(`\n  合計: 候補(${CANDIDATE}) ${tally.candidate} / 現行(sonnet-5) ${tally.baseline} / 引分 ${tally.tie}`
  + (tally.error ? ` / エラー ${tally.error}` : ""));
console.log(`\n→ ${OUT}`);
