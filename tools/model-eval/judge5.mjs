// Phase 5 Step 5: opus-5 ブラインド A/B 判定 (Phase 3 と同一方式: 順序入替 2 回・不一致は tie)
// - 会話: 11 ケース × 3 ペア (gen#0-2 同士) × 候補 2 (qwen-plus / qwen-flash) = 66 ペア
// - フィードバック: 4 ケース × 3 ペア × 候補 2 (qwen-plus / deepseek) = 24 ペア
// - 再生: 2 セッション × 3 窓 × 候補 2 = 12 ペア (窓 = 実学習者発話 + 各モデル自身の AI ターン)
// 各ペア 2 呼び出し → 計 204 judge 呼び出し
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { anthropicJudge, sleep } from "./lib.mjs";

const DIR = new URL(".", import.meta.url).pathname;
const CASES = JSON.parse(readFileSync(`${DIR}fixtures/cases5.json`, "utf8"));
const CONV_SYSTEM = readFileSync(`${DIR}fixtures/system-conversation.txt`, "utf8");
const FB_SYSTEM = readFileSync(`${DIR}fixtures/system-feedback.txt`, "utf8");
const gen = JSON.parse(readFileSync(`${DIR}results5-gen.json`, "utf8"));
const fb = JSON.parse(readFileSync(`${DIR}results5-feedback.json`, "utf8"));
const replay = JSON.parse(readFileSync(`${DIR}results5-replay.json`, "utf8"));
const OUT = `${DIR}results5-judge.json`;

const verdictSchema = {
  type: "object",
  properties: {
    a_score: { type: "integer" }, b_score: { type: "integer" },
    winner: { type: "string", enum: ["A", "B", "tie"] },
    rationale_ja: { type: "string" },
  },
  required: ["a_score", "b_score", "winner", "rationale_ja"], additionalProperties: false,
};

const convJudgeSystem = `You are an expert evaluator for an iOS ESL speaking-practice app. The app currently uses one LLM to script a two-character English conversation ("ESL Group"). We are comparing candidate models against the current one. Model names are hidden; judge only the text.

The production spec every turn must satisfy is below, delimited by <spec> tags. You will then receive the conversation history and two candidate next turns, A and B. The learner utterances come from real speech recognition, so they may contain recognition noise.

<spec>
${CONV_SYSTEM}
</spec>

Judge which candidate is the better next turn for a Japanese adult ESL learner, focusing on SUBJECTIVE quality:
- Naturalness: does it read like real, warm human small talk (spoken aloud via TTS), not stiff or generic?
- Fit for the learner: simple English, short turns, hands the conversation back, keeps the learner talking.
- Character consistency: Chobi = calm warm host with light tsukkomi; Naruko = cheerful fellow learner.
- Situation handling: does it do the right thing for this specific situation (e.g. reacting to content, handling speech-recognition noise or Japanese input per the spec, closing a session, opening a topic)?
Mechanical format compliance (tags, line counts) is checked separately by scripts — only weigh a format issue here if it would badly damage the experience.

Score each candidate 1-10 (10 = ideal turn). winner is the better one, or "tie" if genuinely comparable. Write rationale_ja as 2-4 short sentences in Japanese.`;

const replayJudgeSystem = `You are an expert evaluator for an iOS ESL speaking-practice app. The app scripts a two-character English conversation ("ESL Group") with one LLM. Below is the production spec, then two versions (A and B) of the SAME conversation segment: the learner lines are identical real utterances (from speech recognition, possibly noisy); only the AI script lines differ, because each version was generated by a different hidden model turn-by-turn.

<spec>
${CONV_SYSTEM}
</spec>

Judge which version is the better conversation for a Japanese adult ESL learner over the whole segment:
- Flow and coherence: do the AI turns react to what the learner actually said, keep context from earlier turns, avoid repetition?
- Naturalness and warmth of the small talk; character consistency (Chobi = calm warm host, Naruko = cheerful fellow learner).
- Fit for the learner: simple English, short turns, always handing the conversation back.

Score each version 1-10. winner is the better one, or "tie" if genuinely comparable. Write rationale_ja as 2-4 short sentences in Japanese.`;

const fbJudgeSystem = `You are an expert evaluator for an iOS ESL speaking-practice app. After each session, an LLM generates post-session feedback as JSON (summary / corrections / try_phrases). We are comparing candidate models against the current one. Model names are hidden; judge only the content.

The production feedback spec is below, delimited by <spec> tags. You will then receive the session transcript (real speech-recognition output, possibly noisy) and two candidate feedback JSONs, A and B.

<spec>
${FB_SYSTEM}
</spec>

Judge which candidate is the better feedback for this Japanese adult learner:
- Corrections: are they real learner errors (not AI lines, not speech-recognition artifacts)? Is "improved" natural English? Is "note" accurate, helpful Japanese within ~40 chars? Are the most useful errors chosen?
- Summary: warm, specific, natural Japanese in Chobi's voice (desu-masu), quoting the learner where helpful; follows the spec (no greetings/questions/markdown).
- try_phrases: natural, level-appropriate, genuinely useful for conversations like this one; correct Japanese meanings.
- Overall trustworthiness: no invented errors, no wrong grammar advice, no unnatural Japanese.

Score each candidate 1-10. winner is the better one, or "tie" if genuinely comparable. Write rationale_ja as 2-4 short sentences in Japanese.`;

function toCandidate(winner, candidateIs) {
  if (winner === "tie") return "tie";
  return winner === candidateIs ? "win" : "loss";
}
function combine(v1, v2) {
  const c1 = toCandidate(v1.winner, "A");
  const c2 = toCandidate(v2.winner, "B");
  if (c1 === c2) return c1;
  if (c1 === "tie") return c2;
  if (c2 === "tie") return c1;
  return "tie";
}

// タスクキュー: {key, system, userA, userB} → results.pairs[key] = {verdict, v1, v2}
const results = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")) : { pairs: {} };
const save = () => writeFileSync(OUT, JSON.stringify(results, null, 2));
const tasks = [];

const historyText = (messages) => messages
  .map((m) => (m.role === "user" ? `LEARNER/APP: ${m.content}` : `SCRIPT:\n${m.content}`))
  .join("\n\n");

// 会話ペア
const BASELINE = "sonnet-5";
for (const cand of ["qwen3.7-plus", "qwen3.7-flash"]) {
  for (const c of CASES.conversation) {
    const baseRuns = (gen[BASELINE]?.[c.id] ?? []).filter((r) => !r.error);
    const candRuns = (gen[cand]?.[c.id] ?? []).filter((r) => !r.error);
    for (let i = 0; i < 3; i++) {
      if (!baseRuns[i] || !candRuns[i]) continue;
      const hist = historyText(c.messages);
      const mk = (a, b) => `## Conversation history\n${hist}\n\n## Candidate A next turn\n${a}\n\n## Candidate B next turn\n${b}`;
      tasks.push({
        key: `conv|${cand}|${c.id}|${i}`, system: convJudgeSystem,
        userA: mk(candRuns[i].text, baseRuns[i].text), userB: mk(baseRuns[i].text, candRuns[i].text),
      });
    }
  }
}

// フィードバックペア
for (const cand of ["qwen3.7-plus", "deepseek-v4-flash"]) {
  for (const c of CASES.feedback) {
    const baseRuns = (fb[BASELINE]?.[c.id] ?? []).filter((r) => r.ok);
    const candRuns = (fb[cand]?.[c.id] ?? []).filter((r) => r.ok);
    for (let i = 0; i < 3; i++) {
      if (!baseRuns[i] || !candRuns[i]) continue;
      const mk = (a, b) => `## Session topic\n${c.topic}\n\n## Transcript\n${c.transcript}\n\n## Candidate A feedback JSON\n${a}\n\n## Candidate B feedback JSON\n${b}`;
      tasks.push({
        key: `fb|${cand}|${c.id}|${i}`, system: fbJudgeSystem,
        userA: mk(candRuns[i].text, baseRuns[i].text), userB: mk(baseRuns[i].text, candRuns[i].text),
      });
    }
  }
}

// 再生窓ペア: 学習者発話 + 各モデル自身の AI ターンで窓の transcript を作る
function replayWindow(rc, providerTurns, endTurn, span = 4) {
  const userTurns = rc.history.filter((m) => m.role === "user").map((m) => m.text);
  const lines = [];
  for (let k = Math.max(0, endTurn - span + 1); k <= endTurn; k++) {
    const t = providerTurns.find((x) => x.turn === k);
    if (!t || t.error) return null;
    lines.push(`LEARNER/APP: ${userTurns[k]}`);
    lines.push(`SCRIPT:\n${t.text}`);
  }
  return lines.join("\n\n");
}
for (const cand of ["qwen3.7-plus", "qwen3.7-flash"]) {
  for (const rc of CASES.replay) {
    const baseTurns = replay[BASELINE]?.[rc.id]?.turns ?? [];
    const candTurns = replay[cand]?.[rc.id]?.turns ?? [];
    const n = Math.min(
      baseTurns.filter((t) => !t.error).length,
      candTurns.filter((t) => !t.error).length);
    if (n < 3) continue;
    const windows = [...new Set([Math.floor(n / 3), Math.floor((2 * n) / 3), n - 1])];
    for (const w of windows) {
      const aWin = replayWindow(rc, candTurns, w);
      const bWin = replayWindow(rc, baseTurns, w);
      if (!aWin || !bWin) continue;
      const mk = (a, b) => `## Version A segment\n${a}\n\n## Version B segment\n${b}`;
      tasks.push({
        key: `replay|${cand}|${rc.id}|w${w}`, system: replayJudgeSystem,
        userA: mk(aWin, bWin), userB: mk(bWin, aWin),
      });
    }
  }
}

console.log(`judge pairs: ${tasks.length} (calls: ${tasks.length * 2})`);

const queue = tasks.filter((t) => !results.pairs[t.key]);
let done = tasks.length - queue.length;
async function worker() {
  while (queue.length) {
    const t = queue.shift();
    try {
      const r1 = await anthropicJudge({ system: t.system, messages: [{ role: "user", content: t.userA }], schema: verdictSchema });
      await sleep(150);
      const r2 = await anthropicJudge({ system: t.system, messages: [{ role: "user", content: t.userB }], schema: verdictSchema });
      const verdict = combine(r1.result, r2.result);
      results.pairs[t.key] = { verdict, v1: r1.result, v2: r2.result };
      done++;
      console.log(`[${done}/${tasks.length}] ${t.key} → ${verdict} (${r1.result.a_score}-${r1.result.b_score} / 入替 ${r2.result.a_score}-${r2.result.b_score})`);
    } catch (e) {
      results.pairs[t.key] = { error: String(e.message).slice(0, 300) };
      console.log(`${t.key} ERROR: ${String(e.message).slice(0, 200)}`);
    }
    save();
    await sleep(150);
  }
}
await Promise.all([worker(), worker(), worker()]);
save();

// 集計
console.log("\n== 集計 (candidate 視点 win/tie/loss) ==");
const tally = {};
for (const [key, r] of Object.entries(results.pairs)) {
  if (r.error) continue;
  const [group, cand, cid] = key.split("|");
  const bucket = ((tally[`${group}|${cand}`] ??= { win: 0, tie: 0, loss: 0, byCase: {} }));
  bucket[r.verdict]++;
  (bucket.byCase[cid] ??= []).push(r.verdict);
}
for (const [k, b] of Object.entries(tally)) {
  const n = b.win + b.tie + b.loss;
  const rate = ((b.win + b.tie * 0.5) / n * 100).toFixed(0);
  console.log(`${k}: ${b.win}勝 ${b.tie}分 ${b.loss}敗 (勝率 ${rate}%)`);
  for (const [cid, vs] of Object.entries(b.byCase)) console.log(`   ${cid}: ${vs.join(",")}`);
}
